#!/usr/bin/env python3
"""Generate jog_font.h: 8-bit alpha glyphs from DejaVu at the mock-up sizes."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SANS = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
MONO = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
# chars used on the jog: digits, A-Z, space, punctuation for time/bar
CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ:.-"
FONTS = [
    # name, ttf, size  (sizes match make_bar_mocks.py)
    ("cap",  SANS, 13),
    ("lab12", SANS, 12),
    ("lab11", SANS, 11),
    ("m34",  MONO, 34),
    ("m17",  MONO, 17),
    ("m44",  MONO, 44),
    ("m30",  MONO, 30),
    ("m24",  MONO, 24),
    ("m22",  MONO, 22),
    ("m14",  MONO, 14),
]

def render_font(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    bits = bytearray()
    for ch in CHARS:
        # tight bbox plus a 1 px pad for AA
        bbox = font.getbbox(ch)
        if bbox is None:
            x0 = y0 = 0
            w = h = 0
            adv = 0
        else:
            x0, y0, x1, y1 = bbox
            w, h = x1 - x0, y1 - y0
            adv = int(round(font.getlength(ch)))
        if w <= 0 or h <= 0:
            glyphs.append((ch, 0, 0, 0, 0, max(adv, 0), len(bits)))
            continue
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
        glyphs.append((ch, x0, y0, w, h, adv, len(bits)))
        bits.extend(im.tobytes())
    return {
        'name': name, 'size': size, 'ascent': ascent, 'descent': descent,
        'height': ascent + descent, 'glyphs': glyphs, 'bits': bits,
    }

def c_bytes(data, indent=4):
    lines = []
    row = []
    sp = ' ' * indent
    for i, b in enumerate(data):
        row.append(f'0x{b:02x}')
        if len(row) == 16:
            lines.append(sp + ', '.join(row) + ',')
            row = []
    if row:
        lines.append(sp + ', '.join(row) + ',')
    return '\n'.join(lines)

def main():
    fonts = [render_font(*f) for f in FONTS]
    total = sum(len(f['bits']) for f in fonts)
    out = []
    out.append('/* SPDX-License-Identifier: GPL-3.0-only */')
    out.append('/* Auto-generated by tools/gen_jog_font.py — do not edit.')
    out.append(' * 8-bit alpha glyphs from DejaVu Sans/Sans Mono Bold (Bitstream Vera / DejaVu licence)')
    out.append(f' * at the mock-up sizes in jog-display-research/make_bar_mocks.py. {total} bytes of coverage. */')
    out.append('#ifndef JOG_FONT_H')
    out.append('#define JOG_FONT_H')
    out.append('#include <stdint.h>')
    out.append(f'#define JF_NCHAR {len(CHARS)}')
    out.append(f'#define JF_NFONT {len(FONTS)}')
    out.append('struct jf_glyph { int16_t x, y; uint8_t w, h; int16_t adv; uint32_t off; };')
    out.append('struct jf_font { int size, ascent, height; const struct jf_glyph *g; const uint8_t *bits; uint32_t nbits; };')
    out.append('')
    # char index table
    idx = ['255'] * 128
    for i, ch in enumerate(CHARS):
        idx[ord(ch)] = str(i)
    out.append('static const uint8_t jf_index[128] = {')
    out.append(c_bytes(int(x) if x != '255' else 255 for x in idx))
    # wait, c_bytes expects ints
    out.pop()
    out.append(c_bytes([int(x) for x in idx]))
    out.append('};')
    out.append('')
    for i, f in enumerate(fonts):
        out.append(f'static const uint8_t jf_bits_{f["name"]}[{len(f["bits"])}] = {{')
        out.append(c_bytes(f['bits']))
        out.append('};')
        out.append(f'static const struct jf_glyph jf_glyphs_{f["name"]}[JF_NCHAR] = {{')
        for ch, x, y, w, h, adv, off in f['glyphs']:
            show = ch if ch != ' ' else 'sp'
            out.append(f'    {{ {x:3d}, {y:3d}, {w:3d}, {h:3d}, {adv:3d}, {off:5d} }}, /* {show!r} */')
        out.append('};')
        out.append('')
    out.append('enum {')
    for i, f in enumerate(fonts):
        out.append(f'    JF_{f["name"].upper()} = {i},')
    out.append('};')
    out.append('static const struct jf_font jf_fonts[JF_NFONT] = {')
    for f in fonts:
        out.append(f'    {{ {f["size"]}, {f["ascent"]}, {f["height"]}, jf_glyphs_{f["name"]}, jf_bits_{f["name"]}, {len(f["bits"])} }},')
    out.append('};')
    out.append('#endif')
    dest = ROOT / 'jog_font.h'
    dest.write_text('\n'.join(out) + '\n')
    print(f'wrote {dest} ({dest.stat().st_size} bytes, {total} glyph bytes)')

if __name__ == '__main__':
    main()
